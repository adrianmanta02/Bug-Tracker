package main.milestone.state;

import main.milestone.Milestone;
import main.notification.Notification;

import java.time.LocalDate;

public interface MilestoneState {
    /**
     * Updates the business priority of all tickets associated with the given milestone
     * and validates their developer assignments.
     * For each ticket linked to the milestone:
     * the business priority is advanced to the next level.
     * if the ticket is assigned to a developer who can no longer access it,
     *       the assignment is removed.
     * when an assignment is removed, the ticket status is reset to
     *       {@code OPEN} and a corresponding history entry is recorded.</li>
     * @param milestone the milestone whose tickets are to be updated
     * @param timestamp the timestamp used for history entries generated by this update
     */
    void updateTicketsPriorities(Milestone milestone,
                                 LocalDate timestamp);

    /**
     * Sets the priority for all Tickets involved in the Milestone to
     * CRITICAL, meaning those should have priority when it comes to a
     * Developer having to solve them.
     * @param milestone Milestone instance, having multiple Tickets associated
     */
    void markTicketsCritical(Milestone milestone);

    /**
     * Sends an automatic {@link Notification} for all developers assigned to
     * the Milestone. This usually appears close to due date to alert Developers
     * about tickets needing to be solved quicker.
     * @param milestone Milestone instance in which solving process happens
     * @param notification Notification object sent to all assigned Developers.
     */
    void notifyDevelopers(Milestone milestone, Notification notification);

    /**
     * During an UnlockedState for a Milestone, Developers can take tickets
     * in order to try to solve them.
     * @param milestone instance of Milestone.
     * @return {@code true}, since Milestone's state is on Unlocked
     */
    boolean canPickTickets(Milestone milestone);

    /**
     * Performs automatic updates on Tickets inside a Milestone, depending on
     * the timestamp the check is being made and on due date for Milestone.
     * Marks all tickets on CRITICAL if around deadline and sends a special
     * notification to all developers assigned to the current {@link Milestone}
     * @param milestone Milestone instance
     * @param oneDayBeforeDue boolean value showing if current timestamp is before
     *                        milestone's due date
     * @param oneDayAfterDue boolean value showing if current timestamp is after
     *                       milestone's due date
     */
    void applyTimeBasedRules(Milestone milestone,
                             boolean oneDayBeforeDue,
                             boolean oneDayAfterDue);
    /**
     * Handles the complete update cycle for this state.
     * Checks if state should transition and applies automatic rules.
     *
     * @param milestone the milestone being updated
     * @param currentTimestamp current date
     * @param isCurrentlyBlocked whether the milestone is currently blocked by others
     * @return the new state (might be same state or a different one)
     */
    MilestoneState handleUpdate(Milestone milestone,
                                LocalDate currentTimestamp,
                                boolean isCurrentlyBlocked);
}
